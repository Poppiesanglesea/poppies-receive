CREATE OR REPLACE FUNCTION public.produce_price_for_invoice(p_source_id text, p_dry_run boolean DEFAULT true)
 RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public', 'extensions', 'pg_temp'
AS $function$
declare
  pi record; v_res jsonb; v_new jsonb; v_items bigint[]; v_sup text; v_mode text; v_to text; v_url text;
  n_tag int; n_keep int; n_count int; n_josh int; v_lines text[] := '{}'; v_text text; v_html text; v_subj text;
begin
  select * into pi from processed_invoices where source_id = p_source_id;
  if not found then return jsonb_build_object('ok', false, 'error', 'invoice not booked'); end if;
  if canonical_department(pi.department) <> 'Grocer' then return jsonb_build_object('ok', true, 'skipped', 'not a Grocer invoice'); end if;
  v_sup := canonical_supplier(pi.supplier);
  if v_sup <> all (string_to_array((select value from app_config where key = 'produce_autoprice_suppliers'), ',')) then
    return jsonb_build_object('ok', true, 'skipped', 'supplier not on auto-price list');
  end if;
  v_mode := case when p_dry_run then 'dry_run' else 'live' end;

  select array_agg(distinct l.stock_item_id) into v_items
    from stock_ledger l where l.source = 'invoice:' || p_source_id and l.movement_type = 'delivery';
  v_res := produce_price_items(p_source_id, coalesce(v_items, '{}'), p_dry_run);

  select coalesce(jsonb_agg(jsonb_build_object('name', u.description, 'qty', u.qty, 'unit', u.unit) order by u.description), '[]') into v_new
    from ingest_unmatched u where u.source_tag = 'invoice:' || p_source_id and u.resolved_at is null;

  if not p_dry_run then
    perform delivery_tasks_add(p_source_id, v_res);
    perform delivery_count_tasks_add(p_source_id);
  end if;

  n_tag := jsonb_array_length(v_res->'applied');
  n_keep := jsonb_array_length(v_res->'held') + jsonb_array_length(v_res->'failed');
  n_count := jsonb_array_length(v_new);
  n_josh := n_keep + jsonb_array_length(v_res->'no_price');
  v_url := nullif(btrim(coalesce((select value from app_config where key = 'delivery_app_url'), '')), '');

  if n_tag > 0 then v_lines := v_lines || (n_tag || ' shelf tag' || case when n_tag = 1 then '' else 's' end || ' to change'); end if;
  if n_count > 0 then v_lines := v_lines || (n_count || ' box' || case when n_count = 1 then '' else 'es' end || ' to count'); end if;
  if n_keep > 0 then v_lines := v_lines || (n_keep || ' price' || case when n_keep = 1 then '' else 's' end || ' staying the same for now (leave the tag)'); end if;

  v_subj := format('%s%s delivery is in: %s', case when p_dry_run then '[TEST] ' else '' end, v_sup,
                   coalesce(array_to_string(v_lines[1:2], ', '), 'no tag changes'));
  v_text := case when p_dry_run then E'TEST RUN — nothing has changed in Square or the app.\n\n' else '' end
    || format('%s invoice %s is booked.', v_sup, coalesce(pi.invoice_number, ''))
    || case when cardinality(v_lines) > 0
            then E' Open the New stock app on the shop iPad and tap Deliveries:\n- ' || array_to_string(v_lines, E'\n- ')
            else ' Nothing to change on the shelf.' end
    || case when n_josh > 0 then format(E'\n\nJosh: %s price decision%s waiting in the app.', n_josh, case when n_josh = 1 then '' else 's' end) else '' end
    || case when v_url is not null then E'\n\n' || v_url else '' end;
  v_html := '<div style="font-family:Arial,sans-serif;font-size:15px">'
    || case when p_dry_run then '<p><b>TEST RUN — nothing has changed in Square or the app.</b></p>' else '' end
    || format('<p>%s invoice %s is booked.', v_sup, coalesce(pi.invoice_number, ''))
    || case when cardinality(v_lines) > 0
            then ' Open the <b>New stock app</b> on the shop iPad and tap <b>Deliveries</b>:</p><ul><li>' || array_to_string(v_lines, '</li><li>') || '</li></ul>'
            else ' Nothing to change on the shelf.</p>' end
    || case when n_josh > 0 then format('<p>Josh: %s price decision%s waiting in the app.</p>', n_josh, case when n_josh = 1 then '' else 's' end) else '' end
    || case when v_url is not null then format('<p><a href="%s">Open the app</a></p>', v_url) else '' end
    || '<p style="color:#666;font-size:12px">Sent automatically by Poppie''s when the invoice was booked.</p></div>';
  v_to := (select value from app_config where key = 'produce_price_email_to');

  insert into produce_price_runs (source_id, processed_invoice_id, supplier, invoice_number, invoice_date, mode, applied, held, failed,
                                  email_status, email_to, email_subject, email_text, email_html)
  values (p_source_id, pi.id, v_sup, pi.invoice_number, pi.invoice_date, v_mode, v_res->'applied', v_res->'held', v_res->'failed',
          case when n_tag + n_keep + n_count + n_josh = 0 then 'none' else 'pending' end,
          v_to, v_subj, v_text, v_html)
  on conflict (source_id) do nothing;
  return jsonb_build_object('ok', true, 'mode', v_mode, 'applied', v_res->'applied', 'held', v_res->'held', 'failed', v_res->'failed',
                            'new_items', v_new, 'no_price', v_res->'no_price');
end $function$;
