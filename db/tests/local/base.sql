CREATE OR REPLACE FUNCTION public.delivery_tasks_add(p_source_id text, p_res jsonb)
 RETURNS integer LANGUAGE plpgsql SECURITY DEFINER SET search_path TO 'public'
AS $function$
declare pi record; n int;
begin
  select * into pi from processed_invoices where source_id = p_source_id;
  insert into delivery_tasks (source_id, supplier, invoice_number, invoice_date, department, kind, stock_item_id, square_variation_id, info)
  select p_source_id, canonical_supplier(pi.supplier), pi.invoice_number, pi.invoice_date, canonical_department(pi.department),
         t.kind, (t.x->>'stock_item_id')::bigint, t.x->>'square_variation_id', t.x
    from (select 'tag'::text, x from jsonb_array_elements(coalesce(p_res->'applied', '[]')) x
          union all select 'hold', x from jsonb_array_elements(coalesce(p_res->'held', '[]')) x
          union all select 'hold', x || '{"failed": true}'::jsonb from jsonb_array_elements(coalesce(p_res->'failed', '[]')) x
          union all select 'noprice', x from jsonb_array_elements(coalesce(p_res->'no_price', '[]')) x) t(kind, x)
  on conflict do nothing;
  get diagnostics n = row_count;
  return n;
end $function$;

