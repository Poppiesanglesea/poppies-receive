CREATE OR REPLACE FUNCTION public.delivery_tasks_list()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
begin
  update delivery_tasks t set status = 'closed', done_by = 'system', done_at = now(),
         answer = coalesce(t.answer, '{}'::jsonb) || jsonb_build_object('closed_note', 'matched outside the app')
    from ingest_unmatched u
   where t.kind = 'count' and t.status in ('open', 'escalated') and u.id = t.unmatched_id and u.resolved_at is not null;

  return coalesce((
    select jsonb_agg(c order by (c->>'practice')::boolean, c->>'invoice_date' desc, c->>'source_id')
      from (select jsonb_build_object(
                     'source_id', s.source_id, 'practice', delivery_is_test(s.source_id),
                     'supplier', coalesce(max(t.supplier), max(r.supplier)), 'invoice_number', coalesce(max(t.invoice_number), max(r.invoice_number)),
                     'invoice_date', coalesce(max(t.invoice_date), max(r.invoice_date)), 'department', coalesce(max(t.department), 'Grocer'),
                     'open', count(t.id) filter (where t.status = 'open'),
                     'tasks', coalesce(jsonb_agg(jsonb_build_object(
                         'id', t.id, 'kind', t.kind, 'status', t.status, 'info', t.info - 'candidates', 'done_by', t.done_by, 'done_at', t.done_at,
                         'answer', case when t.kind = 'count' then t.answer - 'map' - 'price' else t.answer end,
                         'candidates', case when t.kind = 'count' and t.status = 'open'
                                            then case when delivery_is_test(t.source_id) then t.info->'candidates' else delivery_count_candidates(t.unmatched_id) end end)
                       order by t.kind, t.info->>'name', t.info->>'description') filter (where t.id is not null), '[]'),
                     'boxes', delivery_box_lines(s.source_id)) c
              from (select d.source_id from delivery_tasks d
                     where d.status = 'open' or d.created_at > now() - interval '24 hours' or d.done_at > now() - interval '24 hours'
                    union
                    select p.source_id from produce_price_runs p where p.mode = 'live' and p.ran_at > now() - interval '48 hours') s
              left join delivery_tasks t on t.source_id = s.source_id
              left join produce_price_runs r on r.source_id = s.source_id
             group by s.source_id) z), '[]');
end $function$
;
