CREATE OR REPLACE FUNCTION public.log_retail_price_change()
 RETURNS trigger
 LANGUAGE plpgsql
 SET search_path TO 'public', 'extensions', 'pg_temp'
AS $function$
begin
  if new.retail_sell_price is distinct from old.retail_sell_price then
    insert into public.retail_price_history
      (stock_item_id, old_price, new_price, unit_cost_at_change, source)
    values (
      new.id,
      old.retail_sell_price,
      new.retail_sell_price,
      (select sp.pack_cost / nullif(sp.pack_grams / nullif(new.grams_per_count_unit, 0), 0)
         from public.supplier_prices sp
        where sp.stock_item_id = new.id
        order by sp.is_preferred desc, sp.effective_from desc, sp.id desc
        limit 1),
      coalesce(nullif(current_setting('poppies.price_source', true), ''), 'manual')
    );
  end if;
  return new;
end
$function$;
