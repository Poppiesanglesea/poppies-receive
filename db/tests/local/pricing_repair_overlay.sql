CREATE VIEW public.v_pricing_policy_for_item AS
 SELECT ssm.stock_item_id,
    ssm.retail_category,
    COALESCE(i.lane, c.lane, d.lane) AS lane,
    COALESCE(i.method, c.method, d.method) AS method,
    COALESCE((i.min_change_cents)::numeric, (c.min_change_cents)::numeric, (d.min_change_cents)::numeric, ( SELECT costing_settings.retail_price_min_change_cents
           FROM costing_settings
          WHERE (costing_settings.id = 1))) AS min_change_cents,
    COALESCE(i.max_change_pct, c.max_change_pct, d.max_change_pct, ( SELECT costing_settings.retail_autopush_max_change_pct
           FROM costing_settings
          WHERE (costing_settings.id = 1))) AS max_change_pct,
        CASE
            WHEN (i.key IS NOT NULL) THEN 'stock_item override'::text
            WHEN (c.key IS NOT NULL) THEN 'retail_category'::text
            ELSE 'default'::text
        END AS policy_source
   FROM (((square_sync_map ssm
     LEFT JOIN pricing_policy i ON (((i.scope = 'stock_item'::text) AND (i.key = (ssm.stock_item_id)::text))))
     LEFT JOIN pricing_policy c ON (((c.scope = 'retail_category'::text) AND (c.key = ssm.retail_category))))
     LEFT JOIN pricing_policy d ON (((d.scope = 'default'::text) AND (d.key = 'default'::text))));

drop table public.v_price_rule_candidates;
CREATE VIEW public.v_price_rule_candidates AS
 WITH ranked AS (
         SELECT sp.stock_item_id,
            sp.pack_cost,
            sp.pack_grams,
            sp.effective_from,
            sp.supplier,
            sp.id,
            row_number() OVER (PARTITION BY sp.stock_item_id ORDER BY sp.effective_from DESC, sp.id DESC) AS rn
           FROM supplier_prices sp
          WHERE (NOT COALESCE(sp.needs_review, false))
        ), cur AS (
         SELECT ranked.stock_item_id,
            ranked.pack_cost,
            ranked.pack_grams,
            ranked.effective_from,
            ranked.supplier,
            ranked.id,
            ranked.rn
           FROM ranked
          WHERE (ranked.rn = 1)
        ), prv AS (
         SELECT ranked.stock_item_id,
            ranked.pack_cost,
            ranked.pack_grams,
            ranked.effective_from,
            ranked.supplier,
            ranked.id,
            ranked.rn
           FROM ranked
          WHERE (ranked.rn = 2)
        ), lastchg AS (
         SELECT DISTINCT ON (h.stock_item_id) h.stock_item_id,
            h.unit_cost_at_change,
            h.changed_at
           FROM retail_price_history h
          ORDER BY h.stock_item_id, h.changed_at DESC
        ), base AS (
         SELECT si.id AS stock_item_id,
            si.name,
            p.retail_category,
            p.lane,
            p.method,
            p.min_change_cents,
            p.max_change_pct,
            p.policy_source,
            ssm.taxable,
            ssm.sync_price,
            ssm.square_variation_id,
            COALESCE(sm.retail_units_base, si.grams_per_count_unit) AS retail_unit_base,
            si.retail_sell_price AS old_price,
            cur.supplier,
            cur.effective_from AS cost_dated,
            lc.changed_at AS last_price_change,
            round(((cur.pack_cost / NULLIF(cur.pack_grams, (0)::numeric)) * COALESCE(sm.retail_units_base, si.grams_per_count_unit)), 4) AS new_cost,
            round(COALESCE(((lc.unit_cost_at_change / NULLIF(si.grams_per_count_unit, (0)::numeric)) * COALESCE(sm.retail_units_base, si.grams_per_count_unit)), ((prv.pack_cost / NULLIF(prv.pack_grams, (0)::numeric)) * COALESCE(sm.retail_units_base, si.grams_per_count_unit))), 4) AS anchor_cost
           FROM ((((((v_pricing_policy_for_item p
             JOIN square_sync_map ssm ON ((ssm.stock_item_id = p.stock_item_id)))
             JOIN stock_items si ON ((si.id = p.stock_item_id)))
             JOIN cur ON ((cur.stock_item_id = si.id)))
             LEFT JOIN prv ON ((prv.stock_item_id = si.id)))
             LEFT JOIN lastchg lc ON ((lc.stock_item_id = si.id)))
             LEFT JOIN square_sales_map sm ON (((sm.square_variation_id = ssm.square_variation_id) AND sm.active)))
          WHERE (si.archived IS NOT TRUE)
        ), calc AS (
         SELECT b.stock_item_id,
            b.name,
            b.retail_category,
            b.lane,
            b.method,
            b.min_change_cents,
            b.max_change_pct,
            b.policy_source,
            b.taxable,
            b.sync_price,
            b.square_variation_id,
            b.retail_unit_base,
            b.old_price,
            b.supplier,
            b.cost_dated,
            b.last_price_change,
            b.new_cost,
            b.anchor_cost,
            round(((100.0 * (b.new_cost - b.anchor_cost)) / NULLIF(b.anchor_cost, (0)::numeric)), 2) AS cost_pct,
                CASE b.method
                    WHEN 'band'::text THEN retail_price_for(b.new_cost, b.retail_category, b.taxable)
                    WHEN 'passthrough'::text THEN
                    CASE
                        WHEN ((b.old_price IS NULL) OR (b.anchor_cost IS NULL) OR (b.anchor_cost = (0)::numeric)) THEN NULL::numeric
                        ELSE round_up_5c(((b.old_price * b.new_cost) / b.anchor_cost))
                    END
                    ELSE NULL::numeric
                END AS proposed_price
           FROM base b
        )
 SELECT stock_item_id,
    name,
    retail_category,
    lane,
    method,
    policy_source,
    supplier,
    cost_dated,
    taxable,
    sync_price,
    square_variation_id,
    retail_unit_base,
    anchor_cost,
    new_cost,
    cost_pct,
    old_price,
    proposed_price,
    round(((100.0 * (proposed_price - old_price)) / NULLIF(old_price, (0)::numeric)), 2) AS price_pct,
    round((100.0 * (proposed_price - old_price))) AS change_cents,
    round(((100.0 * new_cost) / NULLIF((proposed_price /
        CASE
            WHEN taxable THEN 1.10
            ELSE (1)::numeric
        END), (0)::numeric)), 1) AS cogs_pct_after,
    (((100.0 * new_cost) / NULLIF((proposed_price /
        CASE
            WHEN taxable THEN 1.10
            ELSE (1)::numeric
        END), (0)::numeric)) > ( SELECT margin_targets.target_cogs_pct
           FROM margin_targets
          WHERE (margin_targets.item_class = 'retail'::text))) AS below_floor,
        CASE
            WHEN (proposed_price IS NULL) THEN 'no price could be calculated'::text
            WHEN (old_price IS NULL) THEN 'item has no current shelf price'::text
            WHEN ((method = 'band'::text) AND (cost_dated <= COALESCE(((last_price_change AT TIME ZONE 'Australia/Melbourne'::text))::date, '2026-09-27'::date))) THEN 'no new supplier cost since the last price change'::text
            WHEN ((method <> 'band'::text) AND (anchor_cost IS NULL)) THEN 'no earlier cost to compare against'::text
            WHEN (abs(round((100.0 * (proposed_price - old_price)))) < min_change_cents) THEN 'change below the minimum worth relabelling'::text
            ELSE NULL::text
        END AS skip_reason,
    (abs(round(((100.0 * (proposed_price - old_price)) / NULLIF(old_price, (0)::numeric)), 2)) > max_change_pct) AS exceeds_max_pct
   FROM calc c
  WHERE (proposed_price IS DISTINCT FROM old_price);

CREATE OR REPLACE FUNCTION public.produce_price_items(p_source_id text, p_item_ids bigint[], p_dry_run boolean DEFAULT true)
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public', 'extensions', 'pg_temp'
AS $function$
declare
  pi record; r record; v_lbl jsonb; res jsonb; p jsonb;
  v_applied jsonb := '[]'; v_held jsonb := '[]'; v_failed jsonb := '[]'; v_noprice jsonb := '[]'; v_skipped jsonb := '[]';
begin
  select * into pi from processed_invoices where source_id = p_source_id;
  if not found then return jsonb_build_object('ok', false, 'error', 'invoice not booked'); end if;

  for r in
    select c.* from v_price_rule_candidates c
     where c.stock_item_id = any (coalesce(p_item_ids, '{}'))
       and c.retail_category = 'Produce' and c.policy_source = 'retail_category' and c.method = 'band'
       and c.lane <> 'never'
       and (c.skip_reason is null or (c.skip_reason = 'item has no current shelf price' and c.proposed_price is not null))
     order by c.stock_item_id
  loop
    v_lbl := produce_price_label(r.stock_item_id, r.square_variation_id)
             || jsonb_build_object('stock_item_id', r.stock_item_id, 'square_variation_id', r.square_variation_id,
                                   'old', r.old_price, 'new', r.proposed_price, 'pct', r.price_pct);
    if p_dry_run then
      v_applied := v_applied || v_lbl;
      continue;
    end if;
    p := jsonb_build_object('item', r.stock_item_id, 'variation', r.square_variation_id, 'old', r.old_price, 'new', r.proposed_price,
           'method', r.method, 'old_cost', r.anchor_cost, 'new_cost', r.new_cost, 'cost_pct', r.cost_pct, 'price_pct', r.price_pct,
           'cogs_after', r.cogs_pct_after, 'below_floor', r.below_floor, 'source', p_source_id,
           'basis_date', coalesce(pi.invoice_date, pi.processed_at::date), 'basis_seq', pi.id);
    if r.square_variation_id !~ '^[A-Z0-9]{20,}$' then
      v_failed := v_failed || (v_lbl || jsonb_build_object('error', 'no real Square variation id'));
    else
      res := price_propose(p || jsonb_build_object('mode', 'authorised', 'lane', 'auto', 'label', v_lbl,
               'supplier', canonical_supplier(pi.supplier), 'invoice_number', pi.invoice_number, 'invoice_date', pi.invoice_date,
               'department', canonical_department(pi.department),
               'authorised_by', 'auto (markup, Josh 28 Nov): invoice ' || coalesce(pi.invoice_number, p_source_id)));
      if res->>'outcome' = 'authorised' or (res->>'outcome' = 'replay' and coalesce((res->>'task_open')::boolean, false)) then
        v_applied := v_applied || v_lbl;
      else
        v_skipped := v_skipped || (v_lbl || jsonb_build_object('outcome', res->>'outcome', 'status', res->>'status'));
      end if;
    end if;
  end loop;

  select coalesce(jsonb_agg(produce_price_label(c.stock_item_id, c.square_variation_id)
                            || jsonb_build_object('stock_item_id', c.stock_item_id, 'square_variation_id', c.square_variation_id) order by c.name), '[]')
    into v_noprice
    from v_price_rule_candidates c
   where c.stock_item_id = any (coalesce(p_item_ids, '{}')) and c.skip_reason = 'item has no current shelf price'
     and not (c.retail_category = 'Produce' and c.policy_source = 'retail_category' and c.method = 'band'
              and c.lane <> 'never' and c.proposed_price is not null);

  return jsonb_build_object('ok', true, 'applied', v_applied, 'held', v_held, 'failed', v_failed, 'no_price', v_noprice, 'skipped', v_skipped);
end
$function$;

CREATE OR REPLACE FUNCTION public.produce_price_sweep()
 RETURNS jsonb
 LANGUAGE plpgsql
 SECURITY DEFINER
 SET search_path TO 'public'
AS $function$
declare v_mode text := (select value from app_config where key = 'produce_autoprice_mode'); r record; v_out jsonb := '[]';
begin
  if coalesce(v_mode, 'off') = 'off' then return jsonb_build_object('mode', 'off'); end if;
  for r in
    select pi.source_id from processed_invoices pi
     where pi.processed_at >= (select value from app_config where key = 'produce_autoprice_since')::timestamptz
       and canonical_department(pi.department) = 'Grocer'
       and canonical_supplier(pi.supplier) = any (string_to_array((select value from app_config where key = 'produce_autoprice_suppliers'), ','))
       and coalesce(pi.booked_count, 0) > 0
       and not exists (select 1 from produce_price_runs x where x.source_id = pi.source_id)
     order by pi.processed_at limit 5
  loop
    v_out := v_out || jsonb_build_object(r.source_id, produce_price_for_invoice(r.source_id, v_mode <> 'live'));
  end loop;
  if jsonb_array_length(v_out) > 0 then
    insert into engine_runs (steps_ok, steps_failed, notes) values (1, 0, left('PRODUCE-PRICE mode=' || v_mode || ' ' || v_out::text, 500));
  end if;
  return jsonb_build_object('mode', v_mode, 'runs', v_out);
end $function$;

CREATE OR REPLACE FUNCTION public.price_proposal_decide(p_ids bigint[], p_decision text, p_by text DEFAULT 'Josh'::text)
 RETURNS jsonb
 LANGUAGE plpgsql
 SET search_path TO 'public', 'extensions', 'pg_temp'
AS $function$
declare v_n int;
