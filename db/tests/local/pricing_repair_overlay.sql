 RETURNS numeric
 LANGUAGE sql
 IMMUTABLE
 SET search_path TO 'public', 'extensions', 'pg_temp'
AS $function$
  select round_up_5c( net_cost * (1 + markup_pct/100.0) * case when taxable then 1.10 else 1.0 end );
